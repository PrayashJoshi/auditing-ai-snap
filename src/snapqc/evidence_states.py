"""Household draws and evidence states for the confirmatory reader experiment (Design 1 v2).

Households come from the FY2024 QC file; every document is generated by `packets.build_case` plus the deposit
records added here ("QC-grounded synthetic case files"). Nothing in this module selects a household by its
profile: each class is a stratum of the QC file and households are drawn from it at random with one seed.

Classes and the evidence states each one is shown at:
    omission            an earned or unearned group filed at $2 or less with a verified amount above $0 (the
                        185 of the human arm). States: none, deposits_clear, deposits_ambiguous, lead.
    truthful_documented the target group is reported at its verified amount (above $0) with its documents.
                        State: documented.
    zero_rent           the target group is $0 in QC and the household pays rent. State: none.
    zero_stray          the target group is $0 in QC; the file holds one non-recurring credit (the generator's
                        own-account savings transfer). States: stray_clear, stray_ambiguous.
Shelter and utilities are reported at their verified amounts, with their documents, in every input.
"""
from __future__ import annotations

import copy

import numpy as np
import pandas as pd

from . import packets as P
from .calc import inputs as calc_inputs
from .data import RESULTS, SINGLE_SUA_STATES, TOLERANCE
from .forms import GROUPS, sua_tiers

SEED = 20261115
N_OMISSION_PER_TARGET = 12
N_TRUTHFUL_PER_TARGET = 12
N_ZERO_RENT_PER_TARGET = 24
N_ZERO_STRAY_PER_TARGET = 24
N_OMISSIONS_DEFINED = 185
TARGETS = ["earned", "unearned"]

CLASS_STATES = {
    "omission": ["none", "deposits_clear", "deposits_ambiguous", "lead"],
    "truthful_documented": ["documented"],
    "zero_rent": ["none"],
    "zero_stray": ["stray_clear", "stray_ambiguous"],
}
CLASS_SIZE = {"omission": N_OMISSION_PER_TARGET, "truthful_documented": N_TRUTHFUL_PER_TARGET,
              "zero_rent": N_ZERO_RENT_PER_TARGET, "zero_stray": N_ZERO_STRAY_PER_TARGET}
DRAW_ORDER = ["omission", "truthful_documented", "zero_rent", "zero_stray"]

# One label for every relabelled credit, for target deposits and for the stray credit alike, so the label
# itself does not tell the two apart; only recurrence and amount do.
AMBIGUOUS_LABEL = "ACH CREDIT ELECTRONIC DEPOSIT"
SAVINGS_PREFIX = "TRANSFER FROM SAVINGS"

# Deposits for income types whose generator record is a drive income record with no bank trace. They are
# added only in the deposit states of omission households: two monthly credits of the verified amount.
UNLINKED_DEPOSIT_DAY = 7
UNLINKED_LABEL = {
    "SLFEMP": "MERCHANT SERVICES PAYOUT {work}",
    "OTHERN": "P2P PAYMENT RECEIVED ODD JOBS",
    "RENTMINC": "P2P PAYMENT RECEIVED ROOM RENT",
    "CONT": "P2P PAYMENT RECEIVED FROM FAMILY",
    "DEEM": "P2P PAYMENT RECEIVED FROM FAMILY",
    "OTHUN": "MOBILE CHECK DEPOSIT",
    "UNK": "MOBILE CHECK DEPOSIT",
}

LEAD_TEXT = {  # same wording as the first reader run
    "earned": "Agency cross-match lead (IEVS): state wage records show recent quarterly wages for a household member.",
    "unearned": "Agency cross-match lead (IEVS/SSA): external benefit records show recent monthly benefit payments for a household member.",
}


# --- Pools ------------------------------------------------------------------------------------------------
def human_arm() -> pd.DataFrame:
    return pd.read_csv(RESULTS / "01-data-checks" / "3d-human-arm.csv", index_col="row")


def omissions(arm: pd.DataFrame) -> pd.DataFrame:
    """Income omission: an earned or unearned group filed at $2 or less with a verified amount above $0."""
    om = arm[arm["group"].isin(TARGETS) & (arm["filed_value"] <= 2) & (arm["verified_value"] > 0)]
    assert len(om) == N_OMISSIONS_DEFINED, f"omission definition gives {len(om)}, expected {N_OMISSIONS_DEFINED}"
    return om


def ledger_ok(df: pd.DataFrame) -> pd.Series:
    """Person-level income adds up to FSEARN and FSUNEARN within $1 (what `packets.ledger` asserts)."""
    ok = pd.Series(True, index=df.index)
    for types, total in ((P.EARNED_TYPES, "FSEARN"), (P.UNEARNED_TYPES, "FSUNEARN")):
        cols = [f"{t}{p}" for t in types for p in range(1, 19) if f"{t}{p}" in df.columns]
        s = df[cols].fillna(0).sum(axis=1)
        ok &= (s - df[total].fillna(0)).abs() <= 1
    return ok


def pools(df: pd.DataFrame, arm: pd.DataFrame) -> tuple[dict, dict]:
    """Strata to draw from, keyed (class, target), and a log of the exclusions.

    Every pool drops households the generator cannot build faithfully: `calc.benefit` on the verified amounts
    misses FSBEN by more than $1, a utility amount matching none of the state's tiers ("actual costs"), or
    person-level income that does not add up to the household totals. Negative classes come from households
    outside the human arm, in the 41 single-row-SUA states, with AMTERR $56 or less and no MFIP or SSI-CAP unit."""
    calc_ok = (P.qc_benefit(df) - df["FSBEN"]).abs() <= 1
    tier = P.utility_tier(df, sua_tiers(df))
    build_ok = calc_ok & (tier != "actual costs") & ledger_ok(df)
    log = {}
    om = omissions(arm)
    log["omissions (definition)"] = len(om)
    log["omissions: not buildable"] = int((~build_ok[om.index]).sum())
    om = om[build_ok[om.index]]
    neg = df[df["STATENAME"].isin(SINGLE_SUA_STATES) & ~df.index.isin(arm.index)
             & (df["AMTERR"].fillna(0) <= TOLERANCE) & (df["MN_FIP"].fillna(0) != 1) & (df["SSI_CAP"].fillna(0) == 0)]
    log["negative pool (before build filter)"] = len(neg)
    log["negative pool: not buildable"] = int((~build_ok[neg.index]).sum())
    neg = neg[build_ok[neg.index]]
    amt = {"earned": neg["FSEARN"].fillna(0), "unearned": neg["FSUNEARN"].fillna(0)}
    rent = neg["RENT"].fillna(0)
    out = {}
    for g in TARGETS:
        out[("omission", g)] = np.sort(om.index[om["group"] == g].to_numpy())
        out[("truthful_documented", g)] = np.sort(neg.index[amt[g] > 0].to_numpy())
        out[("zero_rent", g)] = np.sort(neg.index[(amt[g] == 0) & (rent > 0)].to_numpy())
        out[("zero_stray", g)] = np.sort(neg.index[amt[g] == 0].to_numpy())
    for k, v in out.items():
        log[f"pool {k[0]} / {k[1]}"] = len(v)
    return out, log | {"tier": tier}


def draw(pool: dict, seed: int = SEED) -> pd.DataFrame:
    """Simple random draws without replacement, one stratum after another in DRAW_ORDER x TARGETS; a household
    drawn once is removed from every later stratum."""
    rng = np.random.default_rng(seed)
    taken: set[int] = set()
    rows = []
    for cls in DRAW_ORDER:
        for g in TARGETS:
            cand = np.array([r for r in pool[(cls, g)] if r not in taken])
            pick = rng.choice(cand, CLASS_SIZE[cls], replace=False)
            for i, r in enumerate(pick):
                rows.append({"row": int(r), "cls": cls, "target_group": g, "draw_index": i})
                taken.add(int(r))
    return pd.DataFrame(rows)


def household_frame(df: pd.DataFrame, arm: pd.DataFrame, drawn: pd.DataFrame, tier: pd.Series) -> pd.DataFrame:
    """Calculator inputs and verified group amounts per drawn household, in the columns `packets` expects."""
    q = df.loc[drawn["row"]]
    ci = calc_inputs(q)
    out = pd.DataFrame({
        "cls": drawn["cls"].to_numpy(), "target_group": drawn["target_group"].to_numpy(),
        "kind": np.where(drawn["cls"] == "omission", "error", "comparison"),
        "group": np.where(drawn["cls"] == "omission", drawn["target_group"], ""),
        "state": q["STATENAME"].to_numpy(), "size": q["FSUSIZE"].astype(int).to_numpy(),
        "utility_tier": tier[q.index].to_numpy(),
        "AMTERR": q["AMTERR"].to_numpy(), "FSBEN": q["FSBEN"].to_numpy(),
        **{f"verified_{g}": ci[a].to_numpy() for g, a in P.GROUP_AMOUNT.items()},
        **{c: ci[c].to_numpy() for c in P.FIXED_AMOUNTS + P.PARAMETERS if c != "size"},
    }, index=pd.Index(drawn["row"].to_numpy(), name="row"))
    out["filed_value"] = arm["filed_value"].reindex(out.index).to_numpy()
    out["verified_value"] = arm["verified_value"].reindex(out.index).to_numpy()
    return out


# --- Evidence states --------------------------------------------------------------------------------------
def add_unlinked_deposits(case: dict, target: str) -> int:
    """Bank credits for target-group facts that leave no bank trace in the generator. Returns how many."""
    n = 0
    for f in case["facts"]:
        if f["group"] != target or P.LINK.get(f["type"]) != "none":
            continue
        label = UNLINKED_LABEL[f["type"]].format(work=str(f.get("work", "")).upper())
        for d in P._month_days(UNLINKED_DEPOSIT_DAY):
            case["records"].append(P._txn(f, d, f["amount"], label))
            n += 1
    return n


def _renumber(docs: list[dict]) -> list[dict]:
    for i, d in enumerate(docs, 1):
        d["id"] = f"doc-{i:02d}"
    return docs


def evidence_packet(case: dict, cls: str, target: str, state: str) -> tuple[dict, dict]:
    """The reader-visible packet (no `sources`) and a scoring-only record of what was kept or changed."""
    case = copy.deepcopy(case)
    n_added = add_unlinked_deposits(case, target) if (cls == "omission" and state.startswith("deposits")) else 0
    full = P.make_packet(case, "complete", {})
    group_of_fact = {f["fact"]: f["group"] for f in case["facts"]}

    def grp(d):
        fid = full["sources"].get(d["id"])
        return group_of_fact.get(fid) if fid else None

    docs = copy.deepcopy(full["documents"])
    for d in docs:
        d["_group"] = grp(d)
    relabelled = 0
    if cls == "omission":
        if state in ("none", "lead"):
            docs = [d for d in docs if d["_group"] != target]
        else:
            docs = [d for d in docs if d["_group"] != target or d["kind"] == "transaction"]
            if state == "deposits_ambiguous":
                for d in docs:
                    if d["_group"] == target and d["kind"] == "transaction":
                        d["data"]["Description"] = AMBIGUOUS_LABEL
                        relabelled += 1
    elif cls == "zero_stray" and state == "stray_ambiguous":
        for d in docs:
            if d["kind"] == "transaction" and d["data"]["Description"].startswith(SAVINGS_PREFIX):
                d["data"]["Description"] = AMBIGUOUS_LABEL
                relabelled += 1
        assert relabelled == 1, f"row {case['row']}: {relabelled} savings transfers"
    target_docs = [d for d in docs if d["_group"] == target]
    meta = {"n_target_docs": len(target_docs), "target_doc_kinds": sorted({d["kind"] for d in target_docs}),
            "n_unlinked_deposits_added": n_added, "n_relabelled": relabelled,
            "doc_groups": [d["_group"] for d in docs]}
    for d in docs:
        del d["_group"]
    packet = {"row": int(full["row"]), "state": full["state"], "sua": copy.deepcopy(full["sua"]),
              "account": full["account"], "window": list(full["window"]), "documents": _renumber(docs)}
    return packet, meta


def application(h: pd.Series, cls: str) -> dict:
    """Monthly amounts per group as the application reports them: verified, except the omission's target at $0."""
    app = {g: float(h[f"verified_{g}"]) for g in GROUPS}
    if cls == "omission":
        app[h["target_group"]] = 0.0
    return app
